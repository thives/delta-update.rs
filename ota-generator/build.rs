
use std::collections::HashMap;
use std::env;
use std::fs;
use std::path::Path;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap_or_else(|_| ".".to_string()));
    println!("cargo:rerun-if-env-changed=GLSLC");
    println!("cargo:rerun-if-changed=shaders");

    write_layout(&out_dir);

    let compiler = env::var("GLSLC").unwrap_or_else(|_| "glslc".to_string());
    let mut stages: Vec<String> = Vec::new();
    let entries = fs::read_dir("shaders").unwrap_or_else(|e| panic!("ota-generator: cannot read shaders/: {}", e));
    for entry in entries {
        let path = entry.unwrap_or_else(|e| panic!("ota-generator: {}", e)).path();
        if path.extension().and_then(|e| e.to_str()) == Some("comp") {
            if let Some(stem) = path.file_stem().and_then(|s| s.to_str()) {
                stages.push(stem.to_string());
            }
        }
    }
    stages.sort();
    let mut table = String::new();
    for name in &stages {
        let source = format!("shaders/{}.comp", name);
        println!("cargo:rerun-if-changed={}", source);
        let target = out_dir.join(format!("{}.spv", name));
        let status = Command::new(&compiler)
            .arg("--target-env=vulkan1.0")
            .arg("-fshader-stage=compute")
            .arg("-O")
            .arg("-Ishaders")
            .arg(&source)
            .arg("-o")
            .arg(&target)
            .status();
        match status {
            Err(e) => panic!(
                "ota-generator: cannot run `{}` to compile {}: {}. Install glslc (Ubuntu: `apt install glslc`) or set GLSLC to its path.",
                compiler, source, e
            ),
            Ok(s) if !s.success() => panic!("ota-generator: `{}` failed on {}", compiler, source),
            Ok(_) => {}
        }
        table.push_str(&format!(
            "pub static {}: &[u8] = include_bytes!({:?});\n",
            name.to_uppercase(),
            target.display().to_string()
        ));
    }
    write(&out_dir.join("gpu_stages.rs"), &table);
}

fn write(path: &Path, text: &str) {
    fs::write(path, text).unwrap_or_else(|e| panic!("ota-generator: cannot write {}: {}", path.display(), e));
}

fn write_layout(out_dir: &Path) {
    let text = fs::read_to_string("shaders/layout.glsl")
        .unwrap_or_else(|e| panic!("ota-generator: cannot read shaders/layout.glsl: {}", e));
    let mut values: HashMap<String, u64> = HashMap::new();
    let mut order: Vec<String> = Vec::new();
    for line in text.lines() {
        let rest = match line.trim().strip_prefix("#define") {
            None => continue,
            Some(r) => r.trim(),
        };
        let (name, expr) = match rest.split_once(char::is_whitespace) {
            None => panic!("layout.glsl: `#define {}` has no value", rest),
            Some((n, e)) => (n.to_string(), e.split("//").next().unwrap_or("").trim().to_string()),
        };
        let value = Parser::new(&expr, &values).run();
        values.insert(name.clone(), value);
        order.push(name);
    }
    let mut out = String::from("// Generated by build.rs from shaders/layout.glsl. Do not edit.\n");
    for name in &order {
        out.push_str(&format!("pub const {}: usize = {};\n", name, values[name]));
    }
    write(&out_dir.join("gpu_layout.rs"), &out);
}

struct Parser<'a> {
    text: Vec<char>,
    at: usize,
    values: &'a HashMap<String, u64>,
}

impl<'a> Parser<'a> {
    fn new(expr: &str, values: &'a HashMap<String, u64>) -> Parser<'a> {
        return Parser {
            text: expr.chars().collect(),
            at: 0,
            values: values,
        };
    }

    fn run(mut self) -> u64 {
        let v = self.shift();
        self.skip();
        if self.at != self.text.len() {
            panic!("layout.glsl: cannot parse `{}`", self.text.iter().collect::<String>());
        }
        return v;
    }

    fn skip(&mut self) {
        while self.at < self.text.len() && self.text[self.at].is_whitespace() {
            self.at += 1;
        }
    }

    fn eat(&mut self, token: &str) -> bool {
        self.skip();
        let t: Vec<char> = token.chars().collect();
        if self.text[self.at..].starts_with(&t) {
            self.at += t.len();
            return true;
        }
        return false;
    }

    fn shift(&mut self) -> u64 {
        let mut v = self.sum();
        loop {
            if self.eat("<<") {
                v <<= self.sum();
            } else if self.eat(">>") {
                v >>= self.sum();
            } else {
                return v;
            }
        }
    }

    fn sum(&mut self) -> u64 {
        let mut v = self.product();
        loop {
            if self.eat("+") {
                v += self.product();
            } else if self.eat("-") {
                v -= self.product();
            } else {
                return v;
            }
        }
    }

    fn product(&mut self) -> u64 {
        let mut v = self.atom();
        loop {
            if self.eat("*") {
                v *= self.atom();
            } else if self.eat("/") {
                v /= self.atom();
            } else if self.eat("%") {
                v %= self.atom();
            } else {
                return v;
            }
        }
    }

    fn atom(&mut self) -> u64 {
        if self.eat("(") {
            let v = self.shift();
            if !self.eat(")") {
                panic!("layout.glsl: missing `)`");
            }
            return v;
        }
        self.skip();
        let start = self.at;
        while self.at < self.text.len() && (self.text[self.at].is_alphanumeric() || self.text[self.at] == '_') {
            self.at += 1;
        }
        let word: String = self.text[start..self.at].iter().collect();
        if word.is_empty() {
            panic!("layout.glsl: expected a value in `{}`", self.text.iter().collect::<String>());
        }
        if word.chars().next().map_or(false, |c| c.is_ascii_digit()) {
            let digits = word.trim_end_matches('u');
            return match digits.strip_prefix("0x") {
                Some(hex) => u64::from_str_radix(hex, 16).unwrap_or_else(|_| panic!("layout.glsl: bad number {}", word)),
                None => digits.parse().unwrap_or_else(|_| panic!("layout.glsl: bad number {}", word)),
            };
        }
        return match self.values.get(&word) {
            Some(v) => *v,
            None => panic!("layout.glsl: `{}` is used before it is defined", word),
        };
    }
}
